import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawn,execFileSync} from 'node:child_process';
import {once} from 'node:events';
import {createHash} from 'node:crypto';
import {ENTRY,observeDispatcherProcess,pinnedDispatcherExpectation} from './dispatch-entrypoint-witness.mjs';

test('real isolated Linux Node process: current entrypoint matches pin, changed bytes hold', {skip:process.platform!=='linux'}, async t=>{
  const repo=fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(),'saban-entrypoint-')));
  const entry=path.join(repo,ENTRY);
  fs.mkdirSync(path.dirname(entry),{recursive:true});
  const bytes="process.stdout.write('ready\\n'); setInterval(()=>{},1000);\n";
  fs.writeFileSync(entry,bytes);
  const git=args=>execFileSync('git',['-C',repo,...args],{stdio:['ignore','pipe','ignore']}).toString().trim();
  git(['init']);git(['add',ENTRY]);
  git(['-c','user.name=Proof','-c','user.email=proof@example.invalid','commit','-m','fixture']);
  const commit=git(['rev-parse','HEAD']);
  const pin=pinnedDispatcherExpectation(repo,commit);
  assert.equal(pin,'sha256:'+createHash('sha256').update(bytes).digest('hex'));
  const child=spawn(process.execPath,[entry,'synthetic-private-argument'],{stdio:['ignore','pipe','ignore']});
  const closed=once(child,'close');
  t.after(async()=>{child.kill();await closed;fs.rmSync(repo,{recursive:true,force:true});});
  await once(child.stdout,'data');
  const good=observeDispatcherProcess({pid:child.pid,repo,expectedSha256:pin});
  assert.equal(good.status,'observed_entrypoint_matched',JSON.stringify(good));
  assert.equal(good.process_identity_stable,true);
  assert.equal(good.loaded_code_verified,false);
  assert.equal(good.work_completed_verified,false);
  assert.equal(JSON.stringify(good).includes('synthetic-private-argument'),false);
  fs.appendFileSync(entry,'// changed after launch\n');
  const changed=observeDispatcherProcess({pid:child.pid,repo,expectedSha256:pin});
  assert.equal(changed.status,'hold');
  assert.equal(changed.reason,'entrypoint_digest_mismatch');
  const other=observeDispatcherProcess({pid:process.pid,repo,expectedSha256:pin});
  assert.equal(other.status,'hold');
  assert.equal(other.current_entrypoint_bytes_matched,false);
  assert.equal(observeDispatcherProcess({pid:0,repo,expectedSha256:pin}).status,'hold');
});

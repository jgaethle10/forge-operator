import assert from 'node:assert/strict';
import {createAdmissionLedger} from './admission-ledger.mjs';
const ledger=createAdmissionLedger({limit:2});
assert.equal(ledger.snapshot().requested,0);
ledger.transition('a','requested');
ledger.transition('b','requested');
ledger.transition('c','requested');
ledger.transition('a','admitted');
ledger.transition('b','admitted');
assert.throws(()=>ledger.transition('c','admitted'),/worker_capacity_exceeded/);
assert.throws(()=>ledger.transition('a','verified'),/invalid_worker_transition/);
ledger.transition('a','provisioned');
ledger.transition('a','running');
assert.equal(ledger.snapshot().running,1);
ledger.transition('a','verified');
assert.equal(ledger.snapshot().verified,1);
ledger.transition('c','admitted');
ledger.transition('c','provisioned');
ledger.transition('c','running');
ledger.transition('c','failed');
assert.equal(ledger.snapshot().failed,1);
assert.equal(ledger.snapshot().visibleCharacters,2);
assert.equal(ledger.transition('a','verified').verified,1);
assert.throws(()=>ledger.transition('a','running'),/invalid_worker_transition/);
assert.throws(()=>createAdmissionLedger({limit:0}),RangeError);
console.log('Work Saban admission ledger PASS: admission limit, real provisioning acknowledgement, terminal states.');

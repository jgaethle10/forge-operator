#!/usr/bin/env bash
# FUNGAL-DEFENSE-001: validation-only handoff for an Evercraft-owned Linux node.
# Fetches canonical source from GitHub; executes offline tests locally;
# stores a JSON receipt; publishes nothing and never touches existing checkouts.
set -Eeuo pipefail
umask 077

BRANCH="research/fungal-defense-001"
ORIGIN="https://github.com/jgaethle10/forge-operator.git"
STATE="${XDG_STATE_HOME:-$HOME/.local/state}/evercraft/fungal-defense"
RECEIPT="$STATE/latest-node-validation.json"
NODE_LABEL="${1:-unverified-local-machine}"

if [[ "${1:-}" == "--help" ]]; then
  printf 'Usage: bash validate_on_owned_node.sh [informational-node-label]\n'
  printf 'This fetches source from GitHub and validates it on THIS computer only.\n'
  exit 0
fi

if ! command -v git >/dev/null || ! command -v python3 >/dev/null; then
  printf 'ERROR: git and python3 are required for local validation.\n' >&2
  exit 2
fi
mkdir -p "$STATE"
WORK="$(mktemp -d "$STATE/source.XXXXXXXX")"
cleanup() {
  # WORK is generated by mktemp under STATE; do not touch other worktrees.
  if [[ "$WORK" == "$STATE"/source.* && -d "$WORK" ]]; then
    rm -rf -- "$WORK"
  fi
}
trap cleanup EXIT

printf 'Fetching canonical research branch into isolated temporary checkout...\n'
export GIT_TERMINAL_PROMPT=0
git clone --quiet --single-branch --branch "$BRANCH" -- "$ORIGIN" "$WORK"
printf 'Executing read-only checks on this machine; no public deployment...\n'
python3 -B "$WORK/research/fungal-defense-001/tools/run_owned_validation.py" \
  --node-label "$NODE_LABEL" --output "$RECEIPT"
printf 'Local validation passed. Receipt: %s\n' "$RECEIPT"
printf 'Public release remains blocked pending independent reviews.\n'

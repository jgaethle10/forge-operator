// HumanFilter regression corpus: synthetic examples, NOT a real-world detection benchmark.
// Run node tests/disclosure_benchmark.cjs from project root.
const assert = require('node:assert/strict');
require('../extension/rules.js');
const {classify,DEFAULTS}=global.HumanFilterRules;
const cases=[
  // Disclosures that should match in Balanced mode, without guessing images.
  ['I made this with AI',1],['I created it using AI',1],
  ['Made using Midjourney',1],['Generated with DALL-E',1],
  ['Created using Stable Diffusion',1],['Produced with Sora',1],
  ['Rendered using AI',1],['Generated by AI',1],
  ['Video was AI-generated',1],['Photo is AI-generated',1],
  ['#aigeneratedart',1],['#madewithai',1],
  ['#aianimation',1],['#aiimage',1],
  ['Made with AI',1],['Created with AI',1],['AI-generated image: beautiful sunset',1],
  ['#AIvideo',1],['I generated this with generative AI',1],
  ['I made it using AI',1],['Illustrated using AI',1],
  // Human-written AI discussion should not get caught in Balanced mode.
  ['Who first coined the phrase artificial intelligence?',0],
  ['I am teaching a course about generative AI ethics',0],
  ['What is the best alternative to ChatGPT?',0],
  ['My grandmother paints portraits in oil',0],
  ['This painting is original, no technology involved',0],
  ['People are debating Midjourney copyright issues',0],
  ['I watched an interview about AI and jobs',0],
  ['We should reduce AI content on social media',0],
  ['Sora is a character in Kingdom Hearts',0],
  ['A video about Stable Diffusion privacy disputes',0],
  ['I enjoy hand-painted fantasy landscapes',0],
  ['A composer explains the history of synthetic instruments',0],
  ['The acronym AI has many meanings',0],
  ['A photographer reviews AI-generated stock imagery',0],
  ['Is it true that AI-generated content can be blocked?',0],
  ['I wrote about how to spot AI art without automation',0],
  ['An artist discusses social media content moderation',0],
  ['The next video discusses deepfake legislation',0],
  ['Kaidance is learning to play piano',0],
  ['The weather is beautiful on this trail',0],
];
let tp=0,tn=0,fp=0,fn=0;
for(const [text,positive] of cases){
  const got=!!classify({site:'youtube',text,labels:[]},DEFAULTS);
  if(positive&&got)tp++; else if(positive)fn++;
  else if(got)fp++; else tn++;
  if(got!==!!positive)console.error('Mismatch:',{text,expected:!!positive,got});
}
const result={synthetic_cases:cases.length,tp,tn,fp,fn};
console.log(JSON.stringify(result));
// Failing means a human-reviewed rule / expectation correction is needed.
assert.equal(fn,0,'missed self-disclosure');
assert.equal(fp,0,'misclassified human discussion');

import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {startWorldsVault} from '../systemia/worlds/worlds-vault-runtime.mjs';
import {createVaultBackup,verifyVaultBackup,restoreVaultBackup} from '../systemia/worlds/worlds-vault-backup.mjs';
import {encodeSharedScene} from '../public/worlds/share-scene.mjs';
import {initialWorld,applyCommand} from '../public/worlds/world-core.mjs';
test('encrypted-at-rest is NOT claimed; private backups verify and recover editable worlds',async t=>{
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'evercraft-worlds-drill-'));
 t.after(()=>fs.rm(root,{recursive:true,force:true}));
 const source=path.join(root,'data'),backups=path.join(root,'backups'),restored=path.join(root,'restored');
 const vault=await startWorldsVault({dataRoot:source,publicRoot:path.resolve('public')});
 let world=applyCommand(initialWorld(),'add tree').world;
 const created=await (await fetch(vault.url+'/worlds/api/worlds',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({scene_token:encodeSharedScene(world)})})).json();
 assert.match(created.edit_token,/^[a-f0-9]{64}$/);
 world=applyCommand(world,'sky night').world;
 const update=await fetch(vault.url+'/worlds/api/worlds/'+created.world_id,{method:'PUT',headers:{'content-type':'application/json','authorization':'Bearer '+created.edit_token,'if-match':'"1"'},body:JSON.stringify({scene_token:encodeSharedScene(world)})});
 assert.equal(update.status,200);
 const receipt=await createVaultBackup({dataRoot:source,backupRoot:backups});
 assert.equal(receipt.world_count,1);
 assert.equal((await verifyVaultBackup(receipt.backup_path)).verified,true);
 const manifest=JSON.parse(await fs.readFile(path.join(receipt.backup_path,'manifest.json'),'utf8'));
 assert.equal('edit_token' in manifest,false);
 assert.equal('edit_hash' in manifest,false);
 await vault.close();
 const resumed=await restoreVaultBackup({backupPath:receipt.backup_path,targetDataRoot:restored});
 assert.equal(resumed.world_count,1);
 await assert.rejects(()=>restoreVaultBackup({backupPath:receipt.backup_path,targetDataRoot:restored}),/must_not_exist/);
 const recovered=await startWorldsVault({dataRoot:restored,publicRoot:path.resolve('public')});
 t.after(()=>recovered.close());
 const read=await (await fetch(recovered.url+'/worlds/api/worlds/'+created.world_id)).json();
 assert.equal(read.version,2);
 assert.equal(read.scene_token,encodeSharedScene(world));
 const upgrade=await fetch(recovered.url+'/worlds/api/worlds/'+created.world_id,{method:'PUT',headers:{'content-type':'application/json','authorization':'Bearer '+created.edit_token,'if-match':'"2"'},body:JSON.stringify({scene_token:encodeSharedScene(world)})});
 assert.equal(upgrade.status,200);
 const file=path.join(receipt.backup_path,created.world_id+'.json');
 await fs.appendFile(file,'X');
 await assert.rejects(()=>verifyVaultBackup(receipt.backup_path),/Unexpected token|invalid|digest|JSON/);
});
test('backup rejects overlap with active vault and nested restore destinations',async t=>{
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'evercraft-worlds-overlap-'));t.after(()=>fs.rm(root,{recursive:true,force:true}));
 const vault=path.join(root,'vault');await fs.mkdir(vault);
 await assert.rejects(()=>createVaultBackup({dataRoot:vault,backupRoot:path.join(vault,'backups')}),/outside_vault/);
 const b=await createVaultBackup({dataRoot:vault,backupRoot:path.join(root,'backups')});
 await assert.rejects(()=>restoreVaultBackup({backupPath:b.backup_path,targetDataRoot:path.join(b.backup_path,'nested')}),/overlap/);
});
